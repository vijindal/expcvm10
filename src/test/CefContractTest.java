    // ── per-quantity checks ──────────────────────────────────────────

    private static void checkG(Case c, CefGibbs g) {
        double actual = g.G(c.T, P_REF, c.y);
        double diff = actual - c.G;
        sumAbsG += Math.abs(diff);
        if (Math.abs(diff) > maxAbsG) { maxAbsG = Math.abs(diff); worstG = where(c); }
        System.out.printf("  G         project=%.4f  pycalphad=%.4f  diff=%.4f%n", actual, c.G, diff);
    }

    private static void checkDgDy(Case c, CefGibbs g) {
        double[] actual = g.dG_dy(c.T, P_REF, c.y);
        double maxDiff = 0;
        for (int i = 0; i < actual.length; i++) {
            double diff = actual[i] - c.dG_dy[i];
            maxDiff = Math.max(maxDiff, Math.abs(diff));
        }
        sumAbsDgDy += maxDiff;
        if (maxDiff > maxAbsDgDy) { maxAbsDgDy = maxDiff; worstDgDy = where(c); }
        System.out.printf("  dG_dy     project=%s%n", Arrays.toString(actual));
        System.out.printf("            pycalphad=%s  maxdiff=%.4f%n", Arrays.toString(c.dG_dy), maxDiff);
    }

    private static void checkD2gDy2(Case c, CefGibbs g) {
        double[][] actual = g.d2G_dy2(c.T, P_REF, c.y);
        double maxDiff = 0;
        int nip = c.y.length;
        for (int i = 0; i < nip; i++) {
            for (int j = 0; j < nip; j++) {
                maxDiff = Math.max(maxDiff, Math.abs(actual[i][j] - c.d2G_dy2[i][j]));
            }
        }
        sumAbsD2gDy2 += maxDiff;
        if (maxDiff > maxAbsD2gDy2) { maxAbsD2gDy2 = maxDiff; worstD2gDy2 = where(c); }
        System.out.printf("  d2G_dy2   maxdiff-vs-pycalphad=%.4f%n", maxDiff);

        // Independent finite-difference cross-check of d2G_dy2 against
        // this project's OWN dG_dy (not pycalphad) -- isolates whether a
        // disagreement (if any, beyond the R-offset already reported
        // above) is in the Hessian formula itself vs. a reference-value
        // transcription issue.
        //
        // y is constrained (each sublattice's constituents sum to 1), so a
        // naive single-index bump y[i] += h leaves the manifold and
        // CefGibbs correctly rejects it (checkY). Instead perturb a PAIR
        // (i, k) in the same sublattice, y[i] += h, y[k] -= h, which stays
        // on the manifold; central-differencing dG_dy along that direction
        // gives the directional second derivative
        //   (H*(e_i - e_k))_j  =  H[i][j] - H[k][j]
        // for every row j -- not each H[i][j] in isolation, but still a
        // real, gated cross-check of the Hessian formula against dG_dy.
        int[] offs = g.offsets();
        int[] ncSL = g.constituentsPerSublattice();
        for (int s = 0; s < g.numSublattices(); s++) {
            if (ncSL[s] < 2) continue; // no pair available on this sublattice
            int i = offs[s];
            int k = offs[s] + 1;
            double[] yPlus = c.y.clone();
            double[] yMinus = c.y.clone();
            yPlus[i] += FD_H; yPlus[k] -= FD_H;
            yMinus[i] -= FD_H; yMinus[k] += FD_H;
            double[] gradPlus = g.dG_dy(c.T, P_REF, yPlus);
            double[] gradMinus = g.dG_dy(c.T, P_REF, yMinus);
            for (int j = 0; j < nip; j++) {
                double fdDirectional = (gradPlus[j] - gradMinus[j]) / (2 * FD_H);
                double analyticDirectional = actual[i][j] - actual[k][j];
                gate("d2G_dy2 directional (i=" + i + ",k=" + k + ")[" + j + "] vs FD(dG_dy)",
                        where(c), fdDirectional, analyticDirectional, 1.0e-1);
            }
        }
    }

    private static void checkDgDT(Case c, CefGibbs g) {
        double actual = g.dG_dT(c.T, P_REF, c.y);
        double diff = actual - c.dG_dT;
        sumAbsDgDT += Math.abs(diff);
        if (Math.abs(diff) > maxAbsDgDT) { maxAbsDgDT = Math.abs(diff); worstDgDT = where(c); }
        System.out.printf("  dG_dT     project=%.6f  pycalphad=%.6f  diff=%.6f%n", actual, c.dG_dT, diff);

        // Independent finite-difference cross-check against this
        // project's own G(T,P,y), central difference in T.
        double gPlus = g.G(c.T + FD_H_T, P_REF, c.y);
        double gMinus = g.G(c.T - FD_H_T, P_REF, c.y);
        double fd = (gPlus - gMinus) / (2 * FD_H_T);
        gate("dG_dT vs FD(G)", where(c), fd, actual, 1.0e-1);
    }

    private static void checkD2gDydT(Case c, CefGibbs g) {
        double[] actual = g.d2G_dydT(c.T, P_REF, c.y);
        double maxDiff = 0;
        for (int i = 0; i < actual.length; i++) {
            maxDiff = Math.max(maxDiff, Math.abs(actual[i] - c.d2G_dydT[i]));
        }
        sumAbsD2gDydT += maxDiff;
        if (maxDiff > maxAbsD2gDydT) { maxAbsD2gDydT = maxDiff; worstD2gDydT = where(c); }
        System.out.printf("  d2G_dydT  maxdiff-vs-pycalphad=%.4f%n", maxDiff);

        // Independent finite-difference cross-check against this
        // project's own dG_dy(T,P,y), central difference in T.
        double[] gradPlus = g.dG_dy(c.T + FD_H_T, P_REF, c.y);
        double[] gradMinus = g.dG_dy(c.T - FD_H_T, P_REF, c.y);
        for (int i = 0; i < actual.length; i++) {
            double fd = (gradPlus[i] - gradMinus[i]) / (2 * FD_H_T);
            gate("d2G_dydT[" + i + "] vs FD(dG_dy)", where(c), fd, actual[i], 1.0e-1);
        }
    }

    private static void checkMoles(Case c, CefGibbs g) {
        double[] actual = g.moles(c.y);
        for (int i = 0; i < c.elements.length; i++) {
            gate("moles[" + c.elements[i] + "]", where(c), actual[i], c.moles[i], GATED_TOL);
        }
    }

    private static void checkDMolesDy(Case c, CefGibbs g) {
        double[][] actual = g.dMoles_dy();
        for (int A = 0; A < c.elements.length; A++) {
            for (int m = 0; m < c.y.length; m++) {
                gate("dMoles_dy[" + c.elements[A] + "][" + m + "]", where(c),
                        actual[A][m], c.dMoles_dy[A][m], GATED_TOL);
            }
        }
    }

    private static void checkDgDpZero(Case c, CefGibbs g) {
        // None of these phases have V0 parameters, so dG_dP must be
        // exactly 0 -- a cheap corroborating check that the pressure
        // contribution correctly no-ops for phases without volume data
        // (see CefVolumeContributionTest for the phases that DO have V0).
        double dGdP = g.dG_dP(c.T, P_REF, c.y);
        gate("dG_dP (no V0 params, expect 0)", where(c), dGdP, 0.0, 1.0e-9);
    }

    // ── shared plumbing ──────────────────────────────────────────────

    private static String where(Case c) {
        return c.phase + " T=" + (int) c.T;
    }

    private static void gate(String label, String where, double actual, double expected, double tol) {
        totalChecks++;
        double diff = Math.abs(actual - expected);
        if (diff > tol) {
            gatedFailures++;
            gatedFailureDetails.add(where + "  " + label
                    + "  actual=" + actual + "  expected=" + expected + "  diff=" + diff);
        }
    }

    private static CefGibbs buildCefGibbs(String tdb, List<String> elements,
                                          String phaseName) throws Exception {
        CalculationSession session = new CalculationSession();
        session.setModel(tdb, elements, Arrays.asList(phaseName));
        List<GibbsEnergyModel> models = session.currentSystem().phaseModels();
        if (models.size() != 1) {
            throw new IllegalStateException("Expected exactly one " + phaseName
                    + " model, but obtained " + models.size());
        }
        GibbsEnergyModel model = models.get(0);
        if (!(model instanceof CefGibbs)) {
            throw new IllegalStateException(phaseName
                    + " was not constructed as a CEF model (got "
                    + model.getClass().getSimpleName() + ").");
        }
        return (CefGibbs) model;
    }

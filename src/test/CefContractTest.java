/**
 * Verifies <b>every quantity on {@link GibbsEnergyModel}'s abstract
 * contract</b> -- the surface a Sundman phase-matrix/equilibrium-matrix
 * solver actually consumes (see {@code calc.equil.PhaseMatrixAssembler}) --
 * against exact symbolic reference values computed from <b>pycalphad
 * 0.11.1</b>.
 *
 * <p>Covers: {@code G}, {@code dG_dy}, {@code d2G_dy2}, {@code dG_dT},
 * {@code d2G_dydT}, {@code moles}, {@code dMoles_dy}. ({@code dG_dP} /
 * {@code d2G_dydP} are covered separately by
 * {@link CefVolumeContributionTest}, the only databases here with active
 * {@code V0} parameters; every phase used below is P-independent, so
 * {@code dG_dP == 0} is asserted here as a cheap corroborating check, not
 * the primary one.)
 *
 * <h2>Why this exists on top of the other CEF tests</h2>
 * {@link CefReferenceTermTest} checks {@code Gref} in isolation at pure
 * end-members; {@link CefMixingTermsTest} checks {@code Gid}/{@code Gex} in
 * isolation, report-only, at interior compositions; {@link
 * CefVolumeContributionTest} checks {@code Gvol}/{@code dG_dP}. None of
 * them touch {@code dG_dy}, {@code d2G_dy2}, {@code d2G_dydT},
 * {@code moles}, or {@code dMoles_dy} -- the exact quantities a Newton
 * solver assembles the phase matrix (Sundman 2015 Eq. 40) and equilibrium
 * matrix (Eq. 58) from. This test is the one place that exercises the full
 * contract surface at once, at the same (T, P, y) point per case, so a
 * single build gives a first-order Taylor-consistent bundle: reference
 * values here were generated by literal symbolic differentiation of
 * pycalphad's {@code Model.GM} (via sympy {@code .diff()}), not finite
 * differences, so {@code dG_dy}/{@code d2G_dy2}/{@code d2G_dydT} are exact
 * to the same precision as {@code G} itself, not merely
 * self-consistent with it.
 *
 * <h2>Fault isolation</h2>
 * Each of the 7 quantities is checked and reported <b>independently per
 * case</b>, never folded into one aggregate pass/fail -- so a wrong sign in
 * one Hessian entry, a wrong RK-order term in one gradient component, or a
 * scale error in {@code dMoles_dy} shows up as a failure naming exactly
 * (phase, T, quantity, index) rather than a single opaque "test failed".
 * {@code d2G_dy2} and {@code dMoles_dy} additionally get an independent
 * finite-difference cross-check against this project's own {@code dG_dy}/
 * {@code moles} (not pycalphad) -- if the FD check disagrees with the
 * analytic method but pycalphad also disagrees, the bug is almost
 * certainly in the analytic derivative formula, not a reference-value
 * transcription error, narrowing the search immediately.
 *
 * <h2>Tolerance</h2>
 * {@code G}, {@code dG_dy}, {@code d2G_dy2} carry the same known constant
 * ideal-mixing offset documented in {@link CefMixingTermsTest} (this
 * project's R = 8.3144598 CODATA-2014 vs. pycalphad's R = 8.31451 SGTE) --
 * report-only, printed but not gated. {@code dG_dT}/{@code d2G_dydT} carry
 * that same offset scaled by the ideal term's R-linearity, also
 * report-only. {@code moles}/{@code dMoles_dy} have no R-dependence at all
 * (pure linear site-fraction combinatorics) and are asserted at tight
 * tolerance -- a failure there is unambiguous and gates the build. The
 * finite-difference cross-checks are likewise gated at tight tolerance
 * since they compare this project against itself, not against pycalphad's
 * R convention.
 *
 * <p>Models are sourced through {@link CalculationSession}, matching the
 * established pattern in the other CEF tests.
 */
